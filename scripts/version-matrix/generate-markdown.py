#!/usr/bin/env python3
"""
Render matrix.json into the version matrix documentation pages.

docs/version-matrix.md has the container images we deploy, the CI tools and the
external Kurtosis packages we pin, each with a status indicator and links to the
deployed and latest upstream versions. docs/hard-forks.md has the hard fork
schedules of the L1 and of the OP Stack L2.
"""

import json
import re
import shutil
import subprocess
from pathlib import Path
from typing import Dict, Optional

from hard_forks import REPO_URL, STATUS_NOT_ENABLED, L1_TEST_CONFIG, L2_INPUT_PARSER

STATUS_EMOJI = {
    "up to date": "✅",
    "ahead": "⚡️",
    "behind": "🚨",
    "pinned": "📌",
}

# Hard fork rows never use 🚨: the bump workflow acts on 🚨 rows, and a fork is
# not something to bump.
FORK_STATUSES = {
    "enabled": ("✅", "Activated by the devnet and known to the pinned clients."),
    "not enabled": ("💤", "Known to the pinned clients, but the devnet leaves it off."),
    "not supported yet": ("⏳", "Exposed by the package, but not known to a pinned client yet."),
    "enabled but unsupported": ("❌", "Configured by the devnet, but a pinned client does not know it and ignores the setting."),
}
STATUS_EMOJI.update({status: emoji for status, (emoji, _) in FORK_STATUSES.items()})

L1_EPOCH_URL = "https://beaconscan.com/epoch/{}"
SEPOLIA_EPOCH_URL = "https://beaconscan.com/sepolia/epoch/{}"

# OP Mainnet Bedrock genesis (superchain-registry op.toml), to turn a fork
# timestamp into a block number.
OP_MAINNET_GENESIS_BLOCK = 105235063
OP_MAINNET_GENESIS_TIME = 1686068903
OP_MAINNET_BLOCK_URL = "https://optimistic.etherscan.io/block/{}"

REGISTRY = "src/package_io/registry.star"


def _short_ref(ref: str) -> str:
    """Shorten commit SHAs like the package table does, but never a tag."""
    return ref[:12] if re.fullmatch(r"[0-9a-f]{40}", ref) else ref


class MarkdownMatrixGenerator:
    """Generates the Markdown version matrix from extracted data."""

    def __init__(self, repo_root: Path):
        self.repo_root = repo_root
        self.matrix_json_path = repo_root / "scripts" / "version-matrix" / "matrix.json"
        self.output_path = repo_root / "docs" / "version-matrix.md"
        self.hard_forks_path = repo_root / "docs" / "hard-forks.md"

    def load_matrix_data(self) -> Dict:
        if not self.matrix_json_path.exists():
            raise FileNotFoundError(
                f"Matrix data not found at {self.matrix_json_path}. "
                f"Run extract-versions.py first.")
        return json.loads(self.matrix_json_path.read_text())

    def generate_markdown_report(self, data: Dict) -> str:
        md = "# Version Matrix\n\n"
        md += "> This page is generated by `scripts/version-matrix`. Do not edit it by hand.\n\n"
        md += "Versions of every component the package deploys, compared against "
        md += "the latest upstream release. Hard forks have their own page: "
        md += "[hard forks](hard-forks.md).\n\n"

        images = data.get("images", {})
        md += "## Images\n\n"
        md += "Container images deployed by the package, pinned in "
        md += f"[`_DEFAULT_IMAGES`]({REPO_URL}/blob/main/{REGISTRY}). "
        md += "A release whose image is not published yet is reported as pinned.\n\n"
        md += "### L1\n\n"
        md += "The package runs the L1 with the ethereum-package default images. "
        md += f"These are the versions the CI pins in [`{L1_TEST_CONFIG}`]({REPO_URL}/blob/main/{L1_TEST_CONFIG}).\n\n"
        md += self._generate_image_table(self._group(images, "l1"))
        md += "\n### L2\n\n"
        md += "What kurtosis-cdk deploys through this package: the default L2 clients, "
        md += "the services every chain gets and the deployer.\n\n"
        md += self._generate_image_table(self._group(images, "l2"))

        skipped = data.get("skipped_images", {})
        if skipped:
            md += "\n### Not tracked\n\n"
            md += "Images this fork does not keep up to date.\n\n"
            md += "| Component | Image | Reason |\n"
            md += "| --- | --- | --- |\n"
            for name, entry in sorted(skipped.items()):
                md += f"| {name} | `{entry['image']}` | {entry['reason']} |\n"

        tools = data.get("tools", {})
        if tools:
            md += "\n## CI tools\n\n"
            md += f"Tools pinned in [`mise.toml`]({REPO_URL}/blob/main/mise.toml) and, for foundry, "
            md += "in the `setup-environment` action.\n\n"
            md += self._generate_image_table(tools, name_header="Tool",
                                             version_header="Pinned version")

        packages = data.get("packages", {})
        if packages:
            md += "\n## Kurtosis packages\n\n"
            md += "External Kurtosis packages the package depends on. Versions are pinned "
            md += f"in the [`replace` block of `kurtosis.yml`]({REPO_URL}/blob/main/kurtosis.yml), "
            md += "which is the single place to bump them.\n\n"
            md += "### Core\n\n"
            md += self._generate_package_table({n: p for n, p in packages.items() if p.get("core")})
            additional = {n: p for n, p in packages.items() if not p.get("core")}
            if additional:
                md += "\n### Additional\n\n"
                md += self._generate_package_table(additional)

        return md

    @staticmethod
    def _group(images: Dict, group: str) -> Dict:
        return {name: c for name, c in images.items() if c.get("group") == group}

    def generate_hard_forks_report(self, forks: Dict) -> str:
        md = "# Hard Forks\n\n"
        md += "> This page is generated by `scripts/version-matrix`. Do not edit it by hand.\n\n"
        md += "Hard forks of the L1 and of the OP Stack L2: when the devnet activates each one, "
        md += "compared with testnet and mainnet and with what the pinned clients support.\n\n"
        md += self._generate_hard_forks(forks)
        return md

    @staticmethod
    def _newest_first(forks: list) -> list:
        """Latest activation first; a fork not scheduled yet comes before any scheduled one."""
        def key(fork):
            return tuple(
                float("inf") if fork.get(field) is None else fork[field]
                for field in ("mainnet", "testnet", "devnet")
            )
        return sorted(reversed(forks), key=key, reverse=True)

    def _generate_hard_forks(self, forks: Dict) -> str:
        md = ""
        l1 = forks["l1"]
        md += "## L1 (Ethereum)\n\n"
        md += "Fork epochs are the ethereum-package `minimal` preset defaults, "
        md += f"overridden in the `network_params` of [`{L1_TEST_CONFIG}`]({REPO_URL}/blob/main/{L1_TEST_CONFIG}).\n\n"
        md += "| CL fork | EL fork | Devnet status | Devnet epoch | Sepolia epoch | Mainnet epoch |\n"
        md += "| --- | --- | --- | --- | --- | --- |\n"
        scheduled = self._newest_first([f for f in l1["forks"] if not self._is_unscheduled(f)])
        for fork in scheduled:
            md += (
                f"| {fork['name']} | {fork.get('el_name') or '—'}"
                f" | {self._status(fork['status'], pin_reason=fork.get('note'))}"
                f" | {self._activation(fork['devnet'])} | {self._testnet(fork, SEPOLIA_EPOCH_URL)}"
                f" | {self._mainnet(fork, L1_EPOCH_URL)} |\n"
            )
        md += f"\n{self._sources(l1)}\n"
        md += self._unscheduled_note([f for f in l1["forks"] if self._is_unscheduled(f)])

        op = forks["op"]
        md += "\n## L2 (OP Stack)\n\n"
        md += "Fork times are offsets in seconds from the L2 genesis: the `<fork>_time_offset` "
        md += f"defaults of [`{L2_INPUT_PARSER}`]({REPO_URL}/blob/main/{L2_INPUT_PARSER}). "
        md += "op-deployer activates a fork left unset at genesis if OP Mainnet has scheduled it "
        md += "in the superchain registry op-deployer embeds. "
        md += "Forks before the first one listed always activate at genesis.\n\n"
        md += "The OP Mainnet column is the first block at the activation time listed in that registry.\n\n"
        md += "| Fork | Devnet status | Devnet offset (s) | OP Mainnet block |\n"
        md += "| --- | --- | --- | --- |\n"
        for fork in self._newest_first(op["forks"]):
            md += (
                f"| {fork['name']}"
                f" | {self._status(fork['status'], pin_reason=fork.get('note'))}"
                f" | {self._activation(fork['devnet'])}"
                f" | {self._mainnet_block(fork)} |\n"
            )
        md += f"\n{self._sources(op)}\n"
        return md

    @staticmethod
    def _sources(section: Dict) -> str:
        """Name the pinned versions a fork table was checked against."""
        links = [f"[{s['name']} {_short_ref(s['ref'])}]({s['url']})"
                 for s in section["sources"]]
        return "Checked against:\n\n" + "\n".join(f"- {link}" for link in links)

    @staticmethod
    def _activation(value: Optional[int]) -> str:
        return "—" if value is None else str(value)

    @staticmethod
    def _is_unscheduled(fork: Dict) -> bool:
        return (fork.get("status") == STATUS_NOT_ENABLED
                and fork.get("testnet") is None
                and fork.get("mainnet") is None)

    @staticmethod
    def _unscheduled_note(forks) -> str:
        if not forks:
            return ""
        items = ", ".join(f"`{f['name']}`" for f in forks)
        return f"\nNot enabled on devnet and not scheduled on testnet or mainnet: {items}.\n"

    @staticmethod
    def _testnet(fork: Dict, url: Optional[str] = None) -> str:
        if fork.get("testnet") is None:
            return "—"
        value = str(fork["testnet"])
        return f"[{value}]({url.format(value)})" if url else value

    @staticmethod
    def _mainnet(fork: Dict, url: Optional[str] = None) -> str:
        if fork.get("mainnet") is not None:
            value = str(fork["mainnet"])
            return f"[{value}]({url.format(value)})" if url else value
        return "—"

    @staticmethod
    def _mainnet_block(fork: Dict) -> str:
        if fork.get("mainnet") is None:
            return "—"
        # OP Mainnet has produced a block every 2s since the Bedrock genesis.
        block = (OP_MAINNET_GENESIS_BLOCK
                 + (fork["mainnet"] - OP_MAINNET_GENESIS_TIME) // 2)
        return f"[{block}]({OP_MAINNET_BLOCK_URL.format(block)})"

    def _generate_image_table(self, images: Dict, name_header: str = "Component",
                              version_header: str = "Deployed version") -> str:
        table = f"| {name_header} | {version_header} | Latest stable version | Status |\n"
        table += "| --- | --- | --- | --- |\n"

        for name, component in sorted(images.items()):
            table += (
                f"| {name}"
                f" | {self._link(component.get('version'), component.get('version_source_url'))}"
                f" | {self._link(component.get('latest_version'), component.get('latest_version_source_url'))}"
                f" | {self._status(component.get('status'), pin_reason=component.get('pin_reason'))} |\n"
            )
        return table

    def _generate_package_table(self, packages: Dict) -> str:
        table = "| Package | Pinned version | Latest stable version | Status |\n"
        table += "| --- | --- | --- | --- |\n"

        for name, package in sorted(packages.items()):
            pin = package.get("pin")
            latest_version = package.get("latest_version")

            # Commit pins are shortened to keep the column narrow; the status
            # column already reports how far a pin has drifted.
            pin_label = pin[:12] if pin and len(pin) > 12 else pin

            # Head-tracked packages release too rarely for a tag to be a useful
            # baseline, so the comparison point is the branch tip. Say so rather
            # than presenting a bare sha as a "stable version".
            latest_label = latest_version
            if latest_version and package.get("tracking_mode") == "head":
                latest_label = f"HEAD ({latest_version[:12]})"

            table += (
                f"| [{name}](https://{name})"
                f" | {self._link(pin_label, package.get('pin_source_url'))}"
                f" | {self._link(latest_label, package.get('latest_version_source_url'))}"
                f" | {self._status(package.get('status'), package.get('commit_distance'), package.get('pin_reason'))} |\n"
            )
        return table

    @staticmethod
    def _link(label: Optional[str], url: Optional[str]) -> str:
        """Render a version as a link to its release, or plain if unknown."""
        if not label:
            return "N/A"
        return f"[{label}]({url})" if url else label

    @staticmethod
    def _status(status: Optional[str], commit_distance: Optional[str] = None,
                pin_reason: Optional[str] = None) -> str:
        """Render a status with its emoji, drift distance and pin reason."""
        if not status:
            return "N/A"

        display = f"{STATUS_EMOJI.get(status, '❓')} {status}"
        if commit_distance:
            display += f" — {commit_distance}"
        if pin_reason:
            display += f" — {pin_reason}"
        return display


def format_with_rumdl(path: Path) -> None:
    """Align the generated tables with `rumdl fmt`.

    The repo lints markdown with MD060 (aligned tables), which pads cells to
    their unicode display width — and the status emojis do not all have the same
    width (✅ is 2 columns, ⚡️ is 1 plus a zero-width variation selector).
    Rather than reimplement that padding and risk drifting from the linter, let
    the linter itself be the source of truth: without this, every generated page
    would fail `rumdl check` and the nightly diff would never be empty.
    """
    if not shutil.which("rumdl"):
        print("Warning: rumdl not found, leaving tables unaligned. "
              "Install it (https://github.com/rvben/rumdl) or run "
              "`rumdl fmt` on the generated page before committing.")
        return

    result = subprocess.run(["rumdl", "fmt", str(path)],
                            capture_output=True, text=True)
    if result.returncode != 0:
        print(f"Warning: `rumdl fmt` failed: {result.stderr.strip()}")


def main():
    repo_root = Path(__file__).parent.parent.parent
    generator = MarkdownMatrixGenerator(repo_root)

    print("Loading matrix data...")
    data = generator.load_matrix_data()

    print("Generating Markdown content...")
    generator.output_path.parent.mkdir(exist_ok=True)
    generator.output_path.write_text(generator.generate_markdown_report(data))
    format_with_rumdl(generator.output_path)
    print(f"Version matrix saved to {generator.output_path}")

    forks = data.get("hard_forks")
    if forks:
        generator.hard_forks_path.write_text(generator.generate_hard_forks_report(forks))
        format_with_rumdl(generator.hard_forks_path)
        print(f"Hard forks saved to {generator.hard_forks_path}")


if __name__ == "__main__":
    main()
